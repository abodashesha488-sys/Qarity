import 'children_speech.dart';

/// 🧒 محتوى التعليم والمهارات لركن الأطفال:
/// أرقام، وضوء، صلاة، قصص الأنبياء، وآداب وسلوكيات — بيانات ثابتة فقط.
class ChildLesson {
  const ChildLesson({
    required this.emoji,
    required this.title,
    required this.body,
    this.tip,
    this.speechText,
  });

  final String emoji;
  final String title;
  final String body;

  /// معلومة إضافية قصيرة (عبرة القصة / نصيحة الأدب).
  final String? tip;

  /// النص الموجه للنطق الصوتي باللهجة المصرية العامية الواضحة والودودة للأطفال.
  final String? speechText;

  /// النص الفعلي الذي يُنطق للأطفال باللهجة المصرية العامية
  String get effectiveSpeech {
    if (speechText != null && speechText!.trim().isNotEmpty) {
      return speechText!;
    }
    final full = '$title. $body${tip == null ? '' : '. $tip'}';
    return ChildrenSpeech.toEgyptianSpeech(full);
  }
}


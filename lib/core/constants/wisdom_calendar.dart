/// النصوص منقولة كما وردت في قائمة القرية، والتصنيف والمناسبة يُعرضان كشارات.
class DayWisdom {
  final String text;
  final String category;
  final String occasion;
  const DayWisdom(this.text, this.category, [this.occasion = 'عامة']);

  bool get isSpecial => occasion != 'عامة';
}

